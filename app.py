# --- API key management (admin console) ---
API_KEY_EXPIRY_CHOICES = {0, 30, 90, 180, 365}
ENV_API_KEY_NAME = "API_KEY"


def _mask_key(key: str) -> str:
    if len(key) <= 16:
        return "•" * 8
    return f"{key[:12]}••••••••{key[-4:]}"


def _require_key_manager(key_ref: str) -> None:
    """Keys created here cannot be used to manage keys; sign in or use the .env key."""
    if key_ref.startswith("apikey:"):
        raise HTTPException(
            status_code=403,
            detail="API keys created in the admin console cannot manage API keys. Sign in as an administrator.",
        )


def _api_keys_payload(db: Session) -> Dict[str, Any]:
    keys = [k.to_dict() for k in db.query(ApiKey).order_by(ApiKey.created_at.desc(), ApiKey.id.desc()).all()]
    env_key = get_configured_api_key() or ""
    week_ago = datetime.now(timezone.utc) - timedelta(days=7)
    return {
        "keys": keys,
        "data": keys,
        "stats": {
            "total": len(keys),
            "active": sum(1 for k in keys if k["status"] == "active"),
            "revoked": sum(1 for k in keys if k["status"] == "revoked"),
            "expired": sum(1 for k in keys if k["status"] == "expired"),
            "usedLast7Days": sum(
                1 for k in keys if k["lastUsedAt"] and datetime.fromisoformat(k["lastUsedAt"]) >= week_ago
            ),
        },
        "envKey": {
            "configured": bool(env_key),
            "name": ENV_API_KEY_NAME,
            "preview": _mask_key(env_key) if env_key else None,
        },
    }


def _get_api_key_or_404(db: Session, key_id: int) -> ApiKey:
    row = db.get(ApiKey, key_id)
    if not row:
        raise HTTPException(status_code=404, detail=f"API key {key_id} not found.")
    return row


