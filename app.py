def _parse_js_items(body: str) -> List[Dict[str, Any]]:
    items: List[Dict[str, Any]] = []
    for obj_match in re.finditer(r"\{([^}]+)\}", body):
        obj_str = obj_match.group(1)
        item: Dict[str, Any] = {}

        m_id = re.search(r"id:\s*'([^']*)'|id:\s*\"([^\"]*)\"", obj_str)
        if m_id:
            item["id"] = m_id.group(1) if m_id.group(1) is not None else m_id.group(2)

        m_title = re.search(r"title:\s*'([^']*)'|title:\s*\"([^\"]*)\"", obj_str)
        if m_title:
            item["title"] = m_title.group(1) if m_title.group(1) is not None else m_title.group(2)

        m_pct = re.search(r"percent:\s*(\d+)", obj_str)
        if m_pct:
            item["percent"] = int(m_pct.group(1))

        m_notes = re.search(r"notes:\s*'([^']*)'|notes:\s*\"([^\"]*)\"", obj_str)
        if m_notes:
            item["notes"] = m_notes.group(1) if m_notes.group(1) is not None else m_notes.group(2)

        if "id" in item:
            items.append(
                {
                    "id": item["id"],
                    "title": item.get("title", ""),
                    "percent": item.get("percent", 0),
                    "notes": item.get("notes", ""),
                }
            )
    return items


def _js_escape(s: str) -> str:
    return (
        s.replace("\\", "\\\\")
        .replace("'", "\\'")
        .replace("\n", "\\n")
        .replace("\r", "\\r")
    )


def _build_js_items(items: List[Dict[str, Any]]) -> str:
    if not items:
        return "\n      "
    lines = []
    for it in items:
        i_id = _js_escape(str(it["id"]))
        i_title = _js_escape(str(it.get("title", "")))
        i_pct = int(it.get("percent", 0))
        i_notes = _js_escape(str(it.get("notes", "")))
        lines.append(
            f"        {{ id: '{i_id}', title: '{i_title}', percent: {i_pct}, notes: '{i_notes}' }},"
        )
    return "\n" + "\n".join(lines) + "\n      "


@app.post("/api/modify_section_defs")
@app.post("/api/modify_section_defs.php")
async def modify_section_defs(
    request: Request,
    db: Session = Depends(get_db),
    _key: str = Depends(require_api_key),
):
    body = await get_json_body(request)
    if not isinstance(body, dict) or "action" not in body or "section" not in body:
        return error_response(400, "Missing required fields: action, section.")

    action = body["action"]
    section = body["section"]
    allowed_sections = {
        "electrical",
        "architectural",
        "mechanical",
        "plumbing",
        "electronics",
        "general",
        "others",
    }
    custom_row = db.get(CustomSection, section) if section not in allowed_sections else None
    if section not in allowed_sections and not custom_row:
        return error_response(400, f"Section not allowed for modification: {section}")
    if custom_row:
        return _modify_custom_section_items(db, custom_row, action, body)

    js_file = FRONTEND_DIR / "state.js"
    if not js_file.exists():
        return error_response(500, "frontend/state.js does not exist.")

    content = js_file.read_text(encoding="utf-8")
    pattern = re.compile(
        r"(" + re.escape(section) + r":\s*\{[^}]*?items:\s*\[)(.*?)(\]\s*\})",
        re.DOTALL,
    )
    match = pattern.search(content)
    if not match:
        return error_response(500, f'Could not locate section "{section}" items in state.js.')

    before_items = match.group(1)
    items_body = match.group(2)
    after_items = match.group(3)
    existing_items = _parse_js_items(items_body)

    if action == "add":
        new_item = body.get("item")
        if not isinstance(new_item, dict) or not new_item.get("id") or not new_item.get("title"):
            return error_response(400, "Missing item.id or item.title.")
        new_id = str(new_item["id"])
        if not any(existing["id"] == new_id for existing in existing_items):
            existing_items.append(
                {
                    "id": new_id,
                    "title": str(new_item["title"]),
                    "percent": 0,
                    "notes": str(new_item.get("notes") or ""),
                }
            )
    elif action == "delete":
        delete_id = body.get("itemId")
        if not delete_id:
            return error_response(400, "Missing itemId.")
        existing_items = [it for it in existing_items if it["id"] != delete_id]
    else:
        return error_response(400, 'Invalid action. Must be "add" or "delete".')

    new_items_body = _build_js_items(existing_items)
    new_block = before_items + new_items_body + after_items
    new_content = content[: match.start()] + new_block + content[match.end() :]

    tmp_file = js_file.with_suffix(f".js.tmp.{os.getpid()}")
    tmp_file.write_text(new_content, encoding="utf-8")
    tmp_file.replace(js_file)

    return send_success({"items": existing_items}, f'Section "{section}" updated successfully.')


