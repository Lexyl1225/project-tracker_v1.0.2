    all_rows = db.query(UserAccount).order_by(UserAccount.id).all()
    stats = {
        "total": sum(1 for u in all_rows if not u.is_deleted),
        "active": sum(1 for u in all_rows if u.is_active and not u.is_deleted),
        "inactive": sum(1 for u in all_rows if not u.is_active and not u.is_deleted),
        "admins": sum(1 for u in all_rows if u.role == "admin" and not u.is_deleted),
        "regular": sum(1 for u in all_rows if u.role != "admin" and not u.is_deleted),
        "deleted": sum(1 for u in all_rows if u.is_deleted),
    }

    filtered: List[UserAccount] = []
