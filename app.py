def get_completed_projects(db: Session = Depends(get_db)):
    try:
        projects = db.query(Project).order_by(Project.title).all()
        completed = []

        for p_row in projects:
            enabled_keys = [
                es.section_key for es in p_row.enabled_sections if es.enabled
            ]
            if not enabled_keys:
                continue

            all_complete = True
            sections_summary: Dict[str, Any] = {}
            sec_by_key = {s.section_key: s for s in p_row.sections}

            for s_key in enabled_keys:
                s_row = sec_by_key.get(s_key)
                if not s_row:
                    all_complete = False
                    break

                tracked_items = [it for it in s_row.items if it.tracked]
                if tracked_items:
                    avg_pct = round(sum(it.percent for it in tracked_items) / len(tracked_items))
                else:
                    avg_pct = 0

                if avg_pct < 100:
                    all_complete = False
                    break

                sections_summary[s_key] = {
                    "title": s_row.title,
                    "percent": int(avg_pct),
                }

            if p_row.status == "completed" or (not p_row.status and all_complete):
                completed.append(
                    {
                        "id": p_row.id,
                        "title": p_row.title,
                        "status": p_row.status or "completed",
                        "overallPercent": _compute_project_percent(p_row),
                        "lastUpdate": format_iso_datetime(p_row.last_update),
                        "lastUpdatedBy": p_row.last_updated_by,
                        "sections": sections_summary,
                    }
                )

        return send_success({"data": completed})
    except Exception as e:
        return error_response(500, f"Failed to load completed projects: {e}")


