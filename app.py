# --- Custom Sections (user-defined disciplines shared by all projects) ---
CUSTOM_SECTION_PALETTE_SIZE = 6
BUILTIN_SECTION_TITLES = {
    "electrical", "architectural", "mechanical", "plumbing", "electronics", "general", "others", "other",
}


def _slug(value: str, max_len: int) -> str:
    return re.sub(r"[^a-z0-9]+", "-", value.lower()).strip("-")[:max_len].strip("-")


def _generate_custom_section_key(db: Session, title: str) -> str:
    base = _slug(title, 24) or "section"
    key = f"c-{base}"
    n = 2
    while key in VALID_SECTIONS or db.get(CustomSection, key):
        suffix = f"-{n}"
        key = f"c-{base[: 28 - len(suffix)]}{suffix}"
        n += 1
    return key


def _next_custom_color_index(db: Session) -> int:
    """First palette colour not used by another custom section (cycles once all are taken)."""
    used = [row[0] for row in db.query(CustomSection.color_index).all()]
    for index in range(CUSTOM_SECTION_PALETTE_SIZE):
        if index not in used:
            return index
    return len(used) % CUSTOM_SECTION_PALETTE_SIZE


def _clean_custom_items(raw: Any) -> List[Dict[str, Any]]:
    """Accept a list of strings or {title, notes} objects and build unique sub-items."""
    items: List[Dict[str, Any]] = []
    seen: set = set()
    for entry in raw if isinstance(raw, list) else []:
        if isinstance(entry, str):
            title, notes = entry.strip(), ""
        elif isinstance(entry, dict):
            title = str(entry.get("title") or "").strip()
            notes = str(entry.get("notes") or "").strip()
        else:
            continue
        if not title:
            continue
        base = _slug(title, 50) or "item"
        item_id, n = base, 2
        while item_id in seen:
            item_id = f"{base}-{n}"
            n += 1
        seen.add(item_id)
        items.append({"id": item_id, "title": title[:255], "percent": 0, "notes": notes})
        if len(items) >= 100:
            break
    return items


def _validate_custom_section_fields(
    db: Session, body: Dict[str, Any], partial: bool, current_key: Optional[str] = None
) -> Dict[str, Any]:
    errors: Dict[str, str] = {}
    clean: Dict[str, Any] = {}
    limits = {"title": 60, "lead": 100, "scope": 300, "summary": 500}
    for field, max_len in limits.items():
        if field not in body:
            continue
        value = str(body.get(field) or "").strip()
        if len(value) > max_len:
            errors[field] = f"must be {max_len} characters or fewer"
        clean[field] = value
    if not partial or "title" in clean:
        title = clean.get("title", "")
        if not title:
            errors["title"] = "is required"
        else:
            bare = re.sub(r"\s+section$", "", title.strip().lower())
            if bare in BUILTIN_SECTION_TITLES:
                errors["title"] = "matches a built-in section; choose a different name"
            else:
                # "Operations" and "Operations Section" display the same, so treat them as duplicates
                dup = next(
                    (
                        row for row in db.query(CustomSection).all()
                        if re.sub(r"\s+section$", "", row.title.strip().lower()) == bare
                        and row.key != current_key
                    ),
                    None,
                )
                if dup:
                    errors["title"] = f"a custom section named '{dup.title}' already exists"
    if errors:
        raise ValidationError(errors)
    return clean


