@app.post("/api/auth/login")
async def login_user(
    request: Request,
    db: Session = Depends(get_db),
):
    """Authenticate a user with username/email + password and return a session token & role."""
    body = await get_json_body(request)
    if not isinstance(body, dict):
        return error_response(400, "Invalid login payload.")

    identifier = str(body.get("username") or body.get("email") or "").strip()
    password = str(body.get("password") or "")

    if not identifier or not password:
        return error_response(400, "Username and password are required.")

    user = (
        db.query(UserAccount)
        .filter(
            (func.lower(UserAccount.username) == identifier.lower())
            | (func.lower(UserAccount.email) == identifier.lower())
        )
        .first()
    )

    if not user or user.is_deleted:
        return error_response(401, "Invalid username or password.")

    if not user.is_active:
        return error_response(403, "This user account has been deactivated. Contact an administrator.")

    if not verify_password(user.username, password, user.secret_hash):
        return error_response(401, "Invalid username or password.")

    # Upgrade legacy hash to PBKDF2 automatically on successful login
    if not user.secret_hash.startswith("pbkdf2:sha256$"):
        user.secret_hash = hash_password(password)

    now = datetime.now(timezone.utc)
    user.last_login_at = now
    session_token = secrets.token_urlsafe(32)
    db.add(
        UserSession(
            token=session_token,
            user_id=user.id,
            expires_at=now + timedelta(days=7),
            created_at=now,
        )
    )
    record_audit_log(
        db,
        action="auth.login",
        target_type="user",
        target_id=str(user.id),
        target_label=user.username,
        actor=user,
        details={"role": user.role},
    )
    db.commit()
    db.refresh(user)

    return send_success(
        {
            "authenticated": True,
            "token": session_token,
            "user": user.to_public_dict(),
        },
        f"Welcome back, {user.full_name or user.username}!",
    )


