@app.post("/api/user_accounts")
@app.post("/api/user_accounts.php")
async def save_user_accounts(
    request: Request,
    db: Session = Depends(get_db),
    _admin: UserAccount = Depends(require_admin),
):
    body = await get_json_body(request)
    if isinstance(body, dict) and isinstance(body.get("accounts"), list):
        body = body["accounts"]
    if not isinstance(body, list):
        return error_response(400, "Expected a JSON array of accounts.")

    try:
        db.query(UserAccount).delete()
        seen = set()
        for acc in body:
            if not isinstance(acc, dict):
                continue
            username = str(acc.get("username") or "").strip()
            secret_hash = str(acc.get("secretHash") or "").strip()
            if not username or not secret_hash or username.lower() in seen:
                continue
            seen.add(username.lower())
            db.add(UserAccount(username=username, secret_hash=secret_hash))
        db.commit()
        return send_success({}, "Accounts saved successfully.")
    except Exception as e:
        db.rollback()
        return error_response(500, f"Failed to save accounts: {e}")


