# --- Gantt Schedule Routes ---
def _calc_duration_days(start_str: str, end_str: str) -> int:
    try:
        s = datetime.strptime(start_str[:10], "%Y-%m-%d")
        e = datetime.strptime(end_str[:10], "%Y-%m-%d")
        return max(1, (e - s).days + 1)
    except Exception:
        return 1


def _parse_dependencies(raw: Any) -> List[str]:
    if isinstance(raw, list):
        return [str(x) for x in raw if x is not None and str(x).strip()]
    if isinstance(raw, str) and raw.strip():
        try:
            parsed = json.loads(raw)
            if isinstance(parsed, list):
                return [str(x) for x in parsed if x is not None and str(x).strip()]
        except Exception:
            return [x.strip() for x in raw.split(",") if x.strip()]
    return []


def _serialize_schedule(sched: GanttSchedule, include_details: bool = True) -> Dict[str, Any]:
    data: Dict[str, Any] = {
        "id": sched.id,
        "project_id": sched.project_id,
        "schedule_name": sched.schedule_name,
        "created_by": sched.created_by,
        "created_at": sched.created_at.strftime("%Y-%m-%d %H:%M:%S") if sched.created_at else "",
        "updated_at": sched.updated_at.strftime("%Y-%m-%d %H:%M:%S") if sched.updated_at else "",
        "status": sched.status,
    }
    if include_details:
        items_sorted = sorted(sched.items, key=lambda x: (x.section_key, x.start_date))
        data["items"] = [
            {
                "id": it.id,
                "schedule_id": it.schedule_id,
                "section_key": it.section_key,
                "item_key": it.item_key,
                "item_title": it.item_title,
                "start_date": it.start_date,
                "end_date": it.end_date,
                "duration_days": it.duration_days,
                "progress": int(it.progress or 0),
                "status": it.status or ("completed" if (it.progress or 0) >= 100 else "in_progress" if (it.progress or 0) > 0 else "not_started"),
                "dependencies": _parse_dependencies(it.dependencies_json),
                "assigned_to": it.assigned_to,
                "priority": it.priority,
                "notes": it.notes,
            }
            for it in items_sorted
        ]
        dist_sorted = sorted(sched.distributions, key=lambda x: x.section_key)
        data["distribution"] = [
            {
                "id": d.id,
                "schedule_id": d.schedule_id,
                "section_key": d.section_key,
                "assigned_team": d.assigned_team,
                "item_count": d.item_count,
                "total_days": d.total_days,
                "start_date": d.start_date,
                "end_date": d.end_date,
                "workload_percent": d.workload_percent,
            }
            for d in dist_sorted
        ]
    return data


