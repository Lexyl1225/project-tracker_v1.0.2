def hash_password(password: str, salt: Optional[str] = None) -> str:
    """Create a PBKDF2-HMAC-SHA256 password hash."""
    if not salt:
        salt = secrets.token_hex(16)
    dk = hashlib.pbkdf2_hmac("sha256", password.encode("utf-8"), salt.encode("utf-8"), 200_000)
    return f"pbkdf2:sha256${salt}${dk.hex()}"


def verify_password(username: str, password: str, stored_hash: str) -> bool:
    """Verify password against PBKDF2 hash or legacy SHA-256 hex digest."""
    if not stored_hash or not password:
        return False
    if stored_hash.startswith("pbkdf2:sha256$"):
        parts = stored_hash.split("$")
        if len(parts) != 3:
            return False
        salt = parts[1]
        expected = hash_password(password, salt=salt)
        return hmac.compare_digest(expected, stored_hash)
    # Legacy SHA-256 hex digest of "<normalized_username>:<password>" or raw password
    combo_digest = hashlib.sha256(f"{username.strip().lower()}:{password}".encode("utf-8")).hexdigest()
    if hmac.compare_digest(combo_digest, stored_hash):
        return True
    raw_digest = hashlib.sha256(password.encode("utf-8")).hexdigest()
    return hmac.compare_digest(raw_digest, stored_hash)


def _ensure_schema_and_seed() -> None:
    """Ensure SQLite columns exist on upgraded databases and seed default Admin/Regular accounts."""
    with engine.begin() as conn:
        if DATABASE_URL.startswith("sqlite"):
            migrations = {
                "projects": [
                    ("description", "TEXT DEFAULT ''"),
                    ("status", " VARCHAR(32) NOT NULL DEFAULT 'in_progress'"),
                    ("created_at", "DATETIME"),
                ],
                "user_accounts": [
                    ("email", "VARCHAR(150)"),
                    ("full_name", "VARCHAR(150) NOT NULL DEFAULT ''"),
                    ("role", "VARCHAR(20) NOT NULL DEFAULT 'regular'"),
                    ("is_active", "BOOLEAN NOT NULL DEFAULT 1"),
                    ("is_deleted", "BOOLEAN NOT NULL DEFAULT 0"),
                    ("deleted_at", "DATETIME"),
                    ("last_login_at", "DATETIME"),
                    ("created_at", "DATETIME"),
                    ("updated_at", "DATETIME"),
                ],
                "gantt_items": [
                    ("progress", "INTEGER NOT NULL DEFAULT 0"),
                    ("status", "VARCHAR(32) NOT NULL DEFAULT 'not_started'"),
                    ("dependencies_json", "TEXT DEFAULT '[]'"),
                ],
            }
            for table_name, cols in migrations.items():
                existing_cols = {
                    row[1]
                    for row in conn.execute(text(f"PRAGMA table_info({table_name})")).fetchall()
                }
                for col_name, col_def in cols:
                    if col_name not in existing_cols:
                        conn.execute(text(f"ALTER TABLE {table_name} ADD COLUMN {col_name} {col_def}"))

    db = SessionLocal()
    try:
        admin_exists = (
            db.query(UserAccount)
            .filter(UserAccount.role == "admin", UserAccount.is_deleted == False)  # noqa: E712
            .first()
        )
        now = datetime.now(timezone.utc)
        if not admin_exists:
            default_admin_user = os.environ.get("ADMIN_USERNAME", "admin")
            default_admin_pass = os.environ.get("ADMIN_PASSWORD", "Admin@123")
            existing_admin_by_name = (
                db.query(UserAccount)
                .filter(func.lower(UserAccount.username) == default_admin_user.lower())
                .first()
            )
            if existing_admin_by_name:
                existing_admin_by_name.role = "admin"
                existing_admin_by_name.is_active = True
                existing_admin_by_name.is_deleted = False
            else:
                db.add(
                    UserAccount(
                        username=default_admin_user,
                        email="admin@projecttracker.local",
                        full_name="System Administrator",
                        secret_hash=hash_password(default_admin_pass),
                        role="admin",
                        is_active=True,
                        is_deleted=False,
                        created_at=now,
                        updated_at=now,
                    )
                )
            db.commit()

        regular_exists = (
            db.query(UserAccount)
            .filter(UserAccount.role == "regular", UserAccount.is_deleted == False)  # noqa: E712
            .first()
        )
        if not regular_exists and db.query(UserAccount).count() <= 1:
            db.add(
                UserAccount(
                    username="engineer",
                    email="engineer@projecttracker.local",
                    full_name="Project Engineer",
                    secret_hash=hash_password("User@123"),
                    role="regular",
                    is_active=True,
                    is_deleted=False,
                    created_at=now,
                    updated_at=now,
                )
            )
            db.commit()
    finally:
        db.close()


_ensure_schema_and_seed()


