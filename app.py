# Failed admin-approval attempts per requesting user: user_id -> [timestamps]
_ADMIN_APPROVAL_FAILURES: Dict[int, List[datetime]] = {}
ADMIN_APPROVAL_MAX_FAILURES = 5
ADMIN_APPROVAL_WINDOW = timedelta(minutes=10)


def _verify_admin_approval(db: Session, requester: UserAccount, body: Any) -> UserAccount:
    """Check an administrator's username + password supplied with a destructive request."""
    now = datetime.now(timezone.utc)
    recent = [t for t in _ADMIN_APPROVAL_FAILURES.get(requester.id, []) if now - t < ADMIN_APPROVAL_WINDOW]
    _ADMIN_APPROVAL_FAILURES[requester.id] = recent
    if len(recent) >= ADMIN_APPROVAL_MAX_FAILURES:
        raise HTTPException(
            status_code=429,
            detail="Too many incorrect administrator passwords. Try again in 10 minutes.",
        )

    data = body if isinstance(body, dict) else {}
    admin_name = str(data.get("adminUsername") or "").strip()
    admin_password = str(data.get("adminPassword") or "")
    if not admin_name or not admin_password:
        raise HTTPException(status_code=400, detail="Administrator username and password are required.")

    admin = (
        db.query(UserAccount)
        .filter(
            (func.lower(UserAccount.username) == admin_name.lower())
            | (func.lower(UserAccount.email) == admin_name.lower()),
            UserAccount.is_deleted == False,  # noqa: E712
            UserAccount.is_active == True,  # noqa: E712
        )
        .first()
    )
    if not admin or admin.role != "admin" or not verify_password(admin.username, admin_password, admin.secret_hash):
        recent.append(now)
        raise HTTPException(status_code=403, detail="Invalid administrator username or password.")
    _ADMIN_APPROVAL_FAILURES.pop(requester.id, None)
    return admin


