def error_response(status: int, message: str, details: Any = None) -> JSONResponse:
    body: Dict[str, Any] = {
        "success": False,
        "error": message,
        "error_detail": {"status": status, "message": message},
    }
    if details:
        body["error_detail"]["details"] = details
        body["details"] = details
    return JSONResponse(status_code=status, content=body)


def send_success(data: Optional[Dict[str, Any]] = None, message: str = "OK") -> JSONResponse:
    payload: Dict[str, Any] = {"success": True, "message": message}
    if data:
        payload.update(data)
    return JSONResponse(status_code=200, content=payload)


