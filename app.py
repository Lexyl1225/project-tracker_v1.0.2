class ApiKey(Base):
    """API key created from the admin console. Only a SHA-256 hash of the key is stored."""

    __tablename__ = "api_keys"

    id = Column(Integer, primary_key=True, autoincrement=True)
    name = Column(String(100), nullable=False)
    key_hash = Column(String(64), unique=True, nullable=False, index=True)
    key_prefix = Column(String(24), nullable=False)
    key_last4 = Column(String(8), nullable=False)
    access = Column(String(10), nullable=False, default="full")  # 'full' | 'read'
    created_by = Column(String(255), nullable=False, default="System")
    created_at = Column(DateTime, nullable=False, default=lambda: datetime.now(timezone.utc))
    expires_at = Column(DateTime, nullable=True)
    last_used_at = Column(DateTime, nullable=True)
    last_used_ip = Column(String(64), nullable=True)
    revoked_at = Column(DateTime, nullable=True)
    revoked_by = Column(String(255), nullable=True)

    def status(self) -> str:
        if self.revoked_at:
            return "revoked"
        if self.expires_at and _as_utc(self.expires_at) <= datetime.now(timezone.utc):
            return "expired"
        return "active"

    def to_dict(self) -> Dict[str, Any]:
        def iso(dt: Optional[datetime]) -> Optional[str]:
            return _as_utc(dt).isoformat() if dt else None

        return {
            "id": self.id,
            "name": self.name,
            "preview": f"{self.key_prefix}…{self.key_last4}",
            "access": self.access or "full",
            "status": self.status(),
            "createdBy": self.created_by,
            "createdAt": iso(self.created_at),
            "expiresAt": iso(self.expires_at),
            "lastUsedAt": iso(self.last_used_at),
            "lastUsedIp": self.last_used_ip,
            "revokedAt": iso(self.revoked_at),
            "revokedBy": self.revoked_by,
        }


def _as_utc(dt: datetime) -> datetime:
    return dt.replace(tzinfo=timezone.utc) if dt.tzinfo is None else dt


