def get_current_user_optional(
    request: Request, db: Session = Depends(get_db)
) -> Optional[UserAccount]:
    token = extract_session_token(request)
    if token:
        sess = db.get(UserSession, token)
        if sess:
            now = datetime.now(timezone.utc)
            exp = sess.expires_at
            if exp.tzinfo is None:
                exp = exp.replace(tzinfo=timezone.utc)
            if exp > now and sess.user and not sess.user.is_deleted and sess.user.is_active:
                return sess.user
    # Fallback header X-User-Name if authenticated via API key
    user_hdr = (request.headers.get("X-User-Name") or "").strip()
    if user_hdr:
        u = (
            db.query(UserAccount)
            .filter(
                func.lower(UserAccount.username) == user_hdr.lower(),
                UserAccount.is_deleted == False,  # noqa: E712
                UserAccount.is_active == True,  # noqa: E712
            )
            .first()
        )
        if u:
            return u
    return None


def require_current_user(
    request: Request,
    db: Session = Depends(get_db),
    _key: str = Depends(require_api_key),
) -> UserAccount:
    user = get_current_user_optional(request, db)
    if user:
        return user
    # If authenticated solely via valid X-API-Key without a session token, resolve default admin
    admin_user = (
        db.query(UserAccount)
        .filter(
            UserAccount.role == "admin",
            UserAccount.is_deleted == False,  # noqa: E712
            UserAccount.is_active == True,  # noqa: E712
        )
        .order_by(UserAccount.id)
        .first()
    )
    if admin_user:
        return admin_user
    raise HTTPException(status_code=401, detail="Authentication required. Please log in.")


def require_admin(
    request: Request,
    db: Session = Depends(get_db),
    _key: str = Depends(require_api_key),
) -> UserAccount:
    token = extract_session_token(request)
    if token:
        sess = db.get(UserSession, token)
        if not sess or not sess.user or sess.user.is_deleted or not sess.user.is_active:
            raise HTTPException(status_code=401, detail="Invalid or expired session token.")
        if sess.user.role != "admin":
            raise HTTPException(
                status_code=403,
                detail="Forbidden: Administrator privileges are required for this action.",
            )
        return sess.user

    role_hdr = (request.headers.get("X-User-Role") or "").strip().lower()
    if role_hdr == "regular":
        raise HTTPException(
            status_code=403,
            detail="Forbidden: Administrator privileges are required for this action.",
        )

    user = require_current_user(request, db, _key)
    if user.role != "admin":
        raise HTTPException(
            status_code=403,
            detail="Forbidden: Administrator privileges are required for this action.",
        )
    return user


