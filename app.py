def _compute_project_percent(p_row: Project) -> int:
    enabled_keys = [es.section_key for es in p_row.enabled_sections if es.enabled]
    if not enabled_keys:
        enabled_keys = [s.section_key for s in p_row.sections]
    if not enabled_keys:
        return 0
    sec_by_key = {s.section_key: s for s in p_row.sections}
    percents: List[int] = []
    for k in enabled_keys:
        s_row = sec_by_key.get(k)
        if not s_row:
            percents.append(0)
            continue
        tracked = [it for it in s_row.items if it.tracked]
        if not tracked:
            percents.append(0)
        else:
            percents.append(round(sum(it.percent for it in tracked) / len(tracked)))
    return round(sum(percents) / len(percents)) if percents else 0


def _load_full_state(db: Session) -> Dict[str, Any]:
    active_row = db.query(ActiveProject).filter(ActiveProject.singleton == 1).first()
    active_project_id = active_row.project_id if active_row else None

    projects_dict: Dict[str, Any] = {}
    project_rows = db.query(Project).order_by(Project.title).all()

    for p_row in project_rows:
        pid = p_row.id
        enabled_sections: Dict[str, bool] = {}
        for es in p_row.enabled_sections:
            enabled_sections[es.section_key] = bool(es.enabled)

        sections_dict: Dict[str, Any] = {}
        for s_row in p_row.sections:
            items_list = [
                {
                    "id": item.item_key,
                    "title": item.title,
                    "percent": int(item.percent),
                    "notes": item.notes,
                    "tracked": bool(item.tracked),
                }
                for item in s_row.items
            ]
            file_name = (s_row.file or "").replace(".php", ".html")
            sections_dict[s_row.section_key] = {
                "title": s_row.title,
                "file": file_name,
                "lead": s_row.lead,
                "scope": s_row.scope,
                "summary": s_row.summary,
                "items": items_list,
            }

        overall_pct = _compute_project_percent(p_row)
        effective_status = p_row.status or ("completed" if overall_pct >= 100 else "in_progress")

        projects_dict[pid] = {
            "id": pid,
            "title": p_row.title,
            "description": p_row.description or "",
            "status": effective_status,
            "overallPercent": overall_pct,
            "createdAt": format_iso_datetime(p_row.created_at),
            "lastUpdate": format_iso_datetime(p_row.last_update),
            "lastUpdatedBy": p_row.last_updated_by,
            "enabledSections": enabled_sections,
            "sections": sections_dict,
        }

    if (not active_project_id or active_project_id not in projects_dict) and projects_dict:
        active_project_id = next(iter(projects_dict.keys()))

    return {
        "activeProjectId": active_project_id,
        "projects": projects_dict,
    }


def _upsert_project(db: Session, project_id: str, project_data: Dict[str, Any]) -> None:
    last_update = parse_iso_datetime(project_data.get("lastUpdate"))
    title = project_data.get("title") or "Project Developments"
    description = project_data.get("description")
    status = project_data.get("status")
    last_updated_by = project_data.get("lastUpdatedBy") or "System"

    p_row = db.get(Project, project_id)
    if p_row is None:
        p_row = Project(
            id=project_id,
            title=title,
            description=str(description or ""),
            status=str(status or "in_progress"),
            created_at=parse_iso_datetime(project_data.get("createdAt")),
            last_update=last_update,
            last_updated_by=last_updated_by,
        )
        db.add(p_row)
        db.flush()
    else:
        p_row.title = title
        if description is not None:
            p_row.description = str(description)
        if status is not None:
            p_row.status = str(status)
        p_row.last_update = last_update
        p_row.last_updated_by = last_updated_by

    db.query(ProjectEnabledSection).filter(
        ProjectEnabledSection.project_id == project_id
    ).delete()

    # Ignore keys of sections that no longer exist (e.g. a custom section deleted while a
    # browser tab still held the old state), so they are not resurrected.
    valid_sections = get_valid_section_keys(db)

    enabled_sections = project_data.get("enabledSections") or {}
    if isinstance(enabled_sections, dict):
        for s_key, enabled in enabled_sections.items():
            if str(s_key) not in valid_sections:
                continue
            db.add(
                ProjectEnabledSection(
                    project_id=project_id,
                    section_key=str(s_key),
                    enabled=bool(enabled),
                )
            )
    elif isinstance(enabled_sections, list):
        for s_key in enabled_sections:
            if str(s_key) not in valid_sections:
                continue
            db.add(
                ProjectEnabledSection(
                    project_id=project_id,
                    section_key=str(s_key),
                    enabled=True,
                )
            )

    # Delete existing sections (cascades to section_items)
    existing_sections = (
        db.query(ProjectSection).filter(ProjectSection.project_id == project_id).all()
    )
    for sec in existing_sections:
        db.delete(sec)
    db.flush()

    sections = project_data.get("sections") or {}
    if isinstance(sections, dict):
        for s_key, sec_data in sections.items():
            if not isinstance(sec_data, dict) or str(s_key) not in valid_sections:
                continue
            file_val = (sec_data.get("file") or "").replace(".php", ".html")
            sec_row = ProjectSection(
                project_id=project_id,
                section_key=str(s_key),
                title=sec_data.get("title") or str(s_key),
                file=file_val,
                lead=sec_data.get("lead") or "",
                scope=sec_data.get("scope"),
                summary=sec_data.get("summary"),
            )
            db.add(sec_row)
            db.flush()

            items = sec_data.get("items") or []
            if isinstance(items, list):
                seen_keys = set()
                for order, item in enumerate(items):
                    if not isinstance(item, dict):
                        continue
                    raw_key = str(item.get("id") or f"item-{order}")
                    item_key = raw_key if raw_key not in seen_keys else f"{raw_key}-{order}"
                    seen_keys.add(item_key)
                    pct = max(0, min(100, int(item.get("percent") or 0)))
                    tracked = bool(item["tracked"]) if "tracked" in item else True
                    db.add(
                        SectionItem(
                            section_id=sec_row.id,
                            item_key=item_key,
                            title=item.get("title") or "",
                            percent=pct,
                            notes=item.get("notes"),
                            tracked=tracked,
                            sort_order=order,
                        )
                    )


