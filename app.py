"""
FastAPI + SQLAlchemy Backend for Project Tracker & REST API.

WHAT THIS API MANAGES
---------------------
1. Project Tracker resources (stored in SQLite `instance/rest_api.db`):
   - Projects, Enabled Sections, Project Sections, Section Sub-items, Active Project
   - User Update Logs (with optional GPS coordinates)
   - Gantt Schedules, Gantt Timeline Items, Work Distributions
   - User Accounts
   - Dynamic Section Definition updates (`frontend/state.js`)

2. Original REST resources:
   - User      - a person              (id, name, description)
   - Favorite  - a saved place/address (id, address, favorite, user_id)

AUTHENTICATION
--------------
Uses API_KEY loaded from `.env` (generated by `api_key_generator.py`).
Clients authenticate via the `X-API-Key` header (or `Authorization: Bearer <API_KEY>`).
Additional keys (full or read-only, optional expiry) can be created and revoked in the
admin console (API Keys tab, `/api/admin/api_keys`); only their SHA-256 hashes are stored.
In the interactive docs (/docs) click "Authorize" and paste the API key.

USERS
-----
- GET /api/users (alias of /api/admin/users): application login accounts (admin access).
- GET /users: the separate "User" REST resource (name/description), not login accounts.

HOW TO RUN
----------
    uvicorn app:app --reload --port 8000
    # or:
    python app.py
"""

