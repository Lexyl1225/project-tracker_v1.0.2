API_KEY_PREFIX = "sk_live_"
READ_ONLY_METHODS = {"GET", "HEAD", "OPTIONS"}
API_KEY_USAGE_THROTTLE = timedelta(seconds=30)


def hash_api_key(key: str) -> str:
    return hashlib.sha256(key.encode("utf-8")).hexdigest()


def extract_api_key(request: Request) -> str:
    """Extract API key from X-API-Key header or Authorization: Bearer header."""
    key = request.headers.get("X-API-Key") or request.headers.get("x-api-key") or ""
    if not key:
        auth = request.headers.get("Authorization") or ""
        if auth.lower().startswith("bearer "):
            key = auth[7:].strip()
    return key.strip()


def extract_session_token(request: Request) -> str:
    """Extract web session token from X-Session-Token or Authorization: Bearer header."""
    token = (
        request.headers.get("X-Session-Token")
        or request.headers.get("x-session-token")
        or ""
    ).strip()
    if not token:
        auth = request.headers.get("Authorization") or ""
        if auth.lower().startswith("bearer "):
            candidate = auth[7:].strip()
            configured_key = get_configured_api_key()
            is_api_key = candidate.startswith(API_KEY_PREFIX) or (configured_key and candidate == configured_key)
            if not is_api_key:
                token = candidate
    return token


# Declared only so /docs shows an "Authorize" button; require_api_key reads the headers itself.
API_KEY_SCHEME = APIKeyHeader(
    name="X-API-Key", auto_error=False, scheme_name="ApiKey",
    description="API_KEY value from .env",
)
SESSION_TOKEN_SCHEME = APIKeyHeader(
    name="X-Session-Token", auto_error=False, scheme_name="SessionToken",
    description="Session token returned by POST /api/auth/login",
)


def require_api_key(
    request: Request,
    db: Session = Depends(get_db),
    _api_key_doc: Optional[str] = Security(API_KEY_SCHEME),
    _session_doc: Optional[str] = Security(SESSION_TOKEN_SCHEME),
) -> str:
    """
    FastAPI Dependency that allows either:
    1) A valid, active web UserSession token (from web login), OR
    2) A valid X-API-Key header matching API_KEY from .env (for direct curl / Invoke-RestMethod queries).
    """
    session_token = extract_session_token(request)
    if session_token:
        sess = db.get(UserSession, session_token)
        if sess:
            now = datetime.now(timezone.utc)
            exp = sess.expires_at
            if exp.tzinfo is None:
                exp = exp.replace(tzinfo=timezone.utc)
            if exp > now and sess.user and not sess.user.is_deleted and sess.user.is_active:
                return f"session:{session_token}"

    configured_key = get_configured_api_key()
    provided = extract_api_key(request)
    if configured_key and provided and hmac.compare_digest(provided, configured_key):
        return provided

    if provided:
        managed = db.query(ApiKey).filter(ApiKey.key_hash == hash_api_key(provided)).first()
        if managed:
            status = managed.status()
            if status != "active":
                raise HTTPException(status_code=401, detail=f"This API key has been {status}.")
            if managed.access == "read" and request.method not in READ_ONLY_METHODS:
                raise HTTPException(
                    status_code=403,
                    detail="This API key is read-only; it can only be used for GET requests.",
                )
            now = datetime.now(timezone.utc)
            if not managed.last_used_at or now - _as_utc(managed.last_used_at) > API_KEY_USAGE_THROTTLE:
                managed.last_used_at = now
                managed.last_used_ip = request.client.host if request.client else None
                db.commit()
            return f"apikey:{managed.id}"

    if configured_key or provided.startswith(API_KEY_PREFIX):
        raise HTTPException(
            status_code=401,
            detail="Missing or invalid API key (send header X-API-Key)",
        )
    return ""


async def get_json_body(request: Request) -> Any:
    try:
        return await request.json()
    except Exception:
        raise ValidationError(
            {"body": 'must be valid JSON sent with header "Content-Type: application/json"'},
            message="Invalid JSON body",
        )


def validate_fields(data: Any, rules: Dict[str, Dict[str, Any]], partial: bool = False) -> Dict[str, Any]:
    if not isinstance(data, dict):
        raise ValidationError(
            {"body": 'must be a JSON object, sent with header "Content-Type: application/json"'},
            message="Invalid JSON body",
        )
    errors: Dict[str, str] = {}
    clean: Dict[str, Any] = {}

    for field, rule in rules.items():
        if field not in data:
            if rule.get("required") and not partial:
                errors[field] = "is required"
            continue

        value = data[field]
        if value is None:
            if rule.get("required"):
                errors[field] = "cannot be null"
            else:
                clean[field] = None
            continue

        expected = rule["type"]
        if not isinstance(value, expected) or (expected is int and isinstance(value, bool)):
            errors[field] = f"must be of type {expected.__name__}"
            continue

        if expected is str:
            value = value.strip()
            if rule.get("required") and not value:
                errors[field] = "cannot be empty"
                continue
            if "max_length" in rule and len(value) > rule["max_length"]:
                errors[field] = f"must be at most {rule['max_length']} characters"
                continue

        clean[field] = value

    if errors:
        raise ValidationError(errors)
    return clean


